<h2 id="part4">Основные методы оценки</h2>
 Основной метод оценки апартаментов — это сравнительный подход с применением корректировок. Отметим, что применение высоких корректировок, которые могут повлиять на итоговую стоимость более, чем на 15-20% — нежелательно. Это может повлечь за собой изменение спроса и сделает отчет оценки уязвимым для критики. Чаще всего корректировки проводятся&nbsp;с ценообразующими факторами второго порядка.
