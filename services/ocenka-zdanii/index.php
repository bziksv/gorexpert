	<h2 id="part2">
	Когда нужна оценка здания:</h2>
	<ul>
		<li>
		При купле-продаже, при разделе, обмене, приватизации, вступления в наследство, дарении и т.д.; </li>
		<li>
		При решении спорных ситуаций, решении имущественных споров. Отчет о стоимости необходим в суде для того, чтоб вынести заключения о страховании; </li>
		<li>
		Для того, чтоб получить кредит; </li>
		<li>
		Для налогообложения; </li>
		<li>
		При выявлении суммы материального ущерба; </li>
		<li>
		При внесении средств в уставный капитал или для их вывода. </li>
		<li>
		Оспаривание кадастровой стоимости </li>
	</ul>
</div>
<p>
	 При этом, оценка может проводиться как по инициативе владельца, так и без нее. Обязательная оценка проводится когда уполномоченные органы для работы нуждаются в заключении о рыночной стоимости здания. Чаще это необходимо во для сделки с недвижимостью.
</p>
<p>
	 Многие полагают, что успех сделки с недвижимостью зависит от стоимости объектов, которая определяется при оценке здания. Конечно, процесс должен учитывать множество факторов, как минимум, состояние постройки. Проще говоря, оценка будет настолько успешной, насколько хорошо хозяин относится к зданию при его продаже. А высокая цена выгодна для продавца недвижимого имущества. Поэтому первое, что важно – это содержание имущества его в надлежащих условиях.
</p>
<p>
	 Расходы на содержание здания могут не окупиться, а цену все равно придется снижать, так как высокая цена отпугивает клиентов. Однако, грамотная и справедливая оценка здания будет полезной как для продавца, так и клиента, так как её цель – держать всех участников сделки в курсе событий.
</p>
<p>
	 Стоит отметить, что косметический ремонт мало влияет на цену здания. Большее значение имеет исправность водопровода и труб, качество электромонтажа в помещениях, целостность крыши и системы отопления. Эти моменты играют большую роль при оценке, нужно содержать все коммуникации в порядке.
</p>
<p>
</p>
