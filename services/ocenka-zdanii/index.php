	<h2 id="part3">Как проводится оценка здания в Санкт-Петербурге</h2>
	<ul>
 <br>
		<li>Производится подача и подписание договора о проведении оценки.<br>
 <br>
 </li>
		<li>Собирается нужная информация, проводится анализ.&nbsp;Специалисты оценщики выезжают на место, делают снимки, расчеты. Согласно итогам работы выводится окончательная рыночная цена. Учитывают&nbsp;характеристики:<br>
 <br>
		<ul>
			<li>расположение&nbsp;собственности, план и границы участка;</li>
			<li>площадь здания, технический паспорт;</li>
			<li>техническое состояние&nbsp;здания (строительно техническая экспертиза) ;</li>
			<li>назначение и др.<br>
 </li>
		</ul>
 </li>
		<li>По результатам проводится подготовка и&nbsp;оформление отчета о стоимости. Данный официальный документ содержит все важные данные, такие как&nbsp;итоговая стоимость и ее обоснование. Отчет дается заказчику и может предоставляться в различных органах.</li>
	</ul>
</div>
<p>
	 Виды стоимости:
</p>
<ul>
	<li>Рыночная - цена, по которой объект может быть продан на свободном рынке;</li>
	<li>Ликвидационная - цена, по которой банк сможет продать имущество в короткий срок при досрочном расторжении ипотечного договора.</li>
</ul>
<p>
	 Оценка здания позволяет дать трезвое заключение по состоянию постройки. И если данная оценка делалась независимо и беспристрастно, то и цена будет справедливой и оправданной. Это значит, что в доме, который купили за большую цену, не нужно будет в будущем делать ремонт или даже генеральную уборку. А чем меньше сумма, тем больше работ в последующем придется в нем сделать. Оценка постройки обязательно расскажет клиентам обо всех этих нюансах через официальные документы, точные цифры и реальные факты, которые указываются в отчете.
</p>
