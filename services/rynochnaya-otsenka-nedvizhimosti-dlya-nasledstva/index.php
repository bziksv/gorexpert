<h2 class="seo-h2">
В каких случаях нотариус может потребовать рыночную оценку</h2>
<p>
	 Если ответить кратко на этот вопрос, то в нотариальной практике такие случаи нередки. Чаще всего, заказать рыночную оценку стоимости наследуемого имущества нужно, если наследники не желают делить между собой несколько объектов в равных долях, а хотят, чтобы каждому из них досталось по целому объекту.
</p>
<p>
	 Так одному из них нужен дом, другому земля, а третий согласен взять себе только авто, а не половину участка, например, цену за половину автомобиля и гаража.
</p>
<p>
	 Для этого необходимо сравнить между собой стоимость каждого объекта, но она в данном случае разная (кадастровая и рыночная — у дома, только рыночная — у авто). В некоторых регионах кадастровая и рыночные цены могут не совпадать, и авто вполне может оказаться дороже дома, поэтому возникает необходимость произвести именно рыночную оценку квартиры, так как она есть у любых объектов.
</p>
