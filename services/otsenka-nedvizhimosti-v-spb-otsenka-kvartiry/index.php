<h2 class="seo-h2" id="_5">Как заказать оценку квартиры</h2>
<p>
	 Звонок в нашу компанию, либо подача заявки на проведение экспертизы через веб-форму, определение конкретных сроков и стоимости работ, а самое главное - формирование задания на оценку.
</p>
<p>
	 Заключение Договора на сотрудничества (типовой договор). Осуществление обязательной фотофиксации квартиры (жилые комнаты, коридоры, вспомогательные помещения, санузлы, кухня, балкон или лоджия, другие фото) и жилого дома (фасад, подъезд к дому, дворовая территория), а также его окружение.
</p>
<div class="seo-highlight-box">
	<p>
		 Выполнение пунктов означает, что заявка обработана и проведены все необходимые подготовительные работы. После этого, в соответствии с ФСО № 1(разд. IV «Требования к проведению оценки», п. 16), оценщик обязан провести следующие мероприятия для определения стоимости квартиры.
	</p>
</div>
<ol>
	<li>Ознакомление с документами, установление количественных и качественных характеристик объекта оценки.</li>
	<li>Объедение детального анализа рынка жилой недвижимости Санкт-Петербурга и, опционально, области (карты, тенденции и ситуация в сегменте рынка недвижимости, которые сложились на дату определения стоимости. Анализ проводится в трех направлениях: анализ спроса, анализ предложения, анализ взаимодействия спроса и предложения. При этом рассматриваются все значимые факторы для данного конкретного типа недвижимости: класс объекта, местоположение, площадь и т.п. Помимо качественного анализа обзор должен содержать количественные данные, подкрепляющие сделанные аналитические выводы), если объект оценки расположен в указанном регионе. В рамках обзора дается прогноз перспектив развития рынка жилой недвижимости.</li>
	<li>Выбор и обоснование подходов к экспертизы и методов оценки в рамках каждого из подходов (как правило, при анализе квартир используется только сравнительный подход. затратный и доходный подходы не распространены в отечественной практике).</li>
	<li>Определение стоимости оцениваемой квартиры в рамках каждого из выбранных подходов к оценке.</li>
	<li>Согласование (обобщение) результатов применения подходов к оценке и определение итоговой величины стоимости оцениваемой квартиры.</li>
	<li>Составление отчета об оценке.</li>
