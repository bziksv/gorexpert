<div class="seo-highlight-box seo-highlight-box--important">
	<p>
		 В соответствии с Федеральными стандартами (ФСО 1-3) для оценки нежилой недвижимости применяются три основных подхода: затратный, сравнительный и доходный. Выбор и комбинация методов зависят от индивидуальных особенностей вашего объекта и целей оценки — будь то сделка купли-продажи, получение кредита в банке или судебные разбирательства в арбитражном суде.
	</p>
</div>
